export const VOCAB_CATEGORY_BY_ID = Object.fromEntries(VOCAB_CATEGORIES.map((c) => [c.id, c]))

export const ALL_VOCAB_WORDS = VOCAB_CATEGORIES.flatMap((c) => c.words)

// Pick 3 wrong options for a "What is this?" quiz for the given word.
export const pickWrongWords = (word, categoryId, count = 3) => {
  const same = VOCAB_CATEGORY_BY_ID[categoryId]?.words || []
  const pool = same.filter((w) => w.word !== word)
  const shuffled = pool.slice().sort(() => Math.random() - 0.5).slice(0, count)
  // if the category is small, add words from other categories
  const extra = ALL_VOCAB_WORDS.filter((w) => w.word !== word && !shuffled.includes(w))
    .sort(() => Math.random() - 0.5)
  while (shuffled.length < count && extra.length) shuffled.push(extra.shift())
  return shuffled.slice(0, count)
}